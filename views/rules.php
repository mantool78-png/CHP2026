    <h2>3. Прогнозы на матчи</h2>
    <p>Участник может оставлять прогнозы на матчи Чемпионата мира по футболу 2026 года.</p>
    <p>Прогноз включает предполагаемый счет матча.</p>
    <p>Во всех матчах конкурса учитывается счет по итогам основного времени матча (90 минут + компенсированное арбитром время).</p>
    <p>Дополнительное время и серия пенальти не учитываются при определении точного счета и исхода матча.</p>
    <p>Для матчей плей-офф ничья по итогам основного времени считается исходом «ничья», даже если одна из команд позже победила в дополнительное время или серии пенальти.</p>
    <p>
        Прием прогнозов на каждый матч заканчивается за
        <strong><?= (int) config('app.prediction_lock_minutes') ?> минут</strong>
        до официального времени начала встречи.
    </p>
    <p>Официальным временем начала матча считается время, указанное на сайте конкурса на момент закрытия приема прогнозов.</p>
    <p>После закрытия приема прогнозов изменить прогноз на данный матч невозможно.</p>
    <p>Если организатор конкурса уже внес официальный счет матча либо отметил матч завершенным, прием прогнозов на этот матч считается закрытым, в том числе для новых участников.</p>
    <p>До начала матча прогнозы других участников скрыты.</p>
    <p>После начала матча прогнозы всех участников становятся открытыми для просмотра.</p>
    <p>Все сроки и время, указанные на сайте конкурса, отображаются по московскому времени (МСК).</p>

    <h2>4. Начисление очков</h2>
    <p>Очки начисляются после завершения матча и внесения официального результата организатором конкурса.</p>
    <p>Начисление очков:</p>
    <ul>
        <li><strong>1 очко</strong> — за угаданный исход матча;</li>
        <li><strong>3 очка</strong> — за угаданный точный счет матча;</li>
        <li><strong>10 очков</strong> — за правильно угаданного чемпиона мира.</li>
    </ul>
    <p>Исходом матча считается:</p>
    <ul>
        <li>победа первой команды;</li>
        <li>ничья;</li>
        <li>победа второй команды;</li>
    </ul>
    <p>по итогам основного времени матча.</p>
    <p>Если участник угадал точный счет, он получает 3 очка за матч.</p>
    <p>Дополнительное очко за исход в этом случае не начисляется.</p>

